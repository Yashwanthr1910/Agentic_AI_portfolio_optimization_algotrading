def test_mpt_covariance_symbols_equal_eligible_symbols():
    """
    Covariance matrix must contain exactly the MPT-eligible assets.
    """

    dataframe = (
        load_rebalancing_input()
    )

    eligible = normalize_bool(
        dataframe[
            "eligible_for_mpt"
        ]
    )

    eligible_symbols = set(
        dataframe.loc[
            eligible,
            "symbol",
        ]
        .astype(str)
    )

    covariance = pd.read_csv(
        cfg.COVARIANCE_MATRIX_CSV,
        index_col=0,
    )

    covariance_symbols = set(
        covariance.columns.astype(
            str
        )
    )

    assert covariance_symbols == eligible_symbols



def test_covariance_matrix_positive_semidefinite():
    """
    Valid covariance matrices must be positive semidefinite.
    """

    covariance = pd.read_csv(
        cfg.COVARIANCE_MATRIX_CSV,
        index_col=0,
    )

    values = covariance.to_numpy(
        dtype=float
    )

    eigenvalues = np.linalg.eigvalsh(
        values
    )

    assert np.min(
        eigenvalues
    ) >= -1e-8



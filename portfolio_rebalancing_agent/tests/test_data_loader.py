def load_returns() -> pd.DataFrame:
    """
    Load Agent-5 return matrix.
    """

    if cfg.RETURNS_MATRIX_PARQUET.exists():

        dataframe = pd.read_parquet(
            cfg.RETURNS_MATRIX_PARQUET
        )

    elif cfg.RETURNS_MATRIX_CSV.exists():

        dataframe = pd.read_csv(
            cfg.RETURNS_MATRIX_CSV
        )

    else:

        raise FileNotFoundError(
            "Agent-5 return matrix not found."
        )

    assert "date" in dataframe.columns

    dataframe[
        "date"
    ] = pd.to_datetime(
        dataframe[
            "date"
        ],
        errors="coerce",
    )

    assert not dataframe[
        "date"
    ].isna().any()

    return (
        dataframe
        .set_index("date")
        .sort_index()
    )


def load_rebalancing_input() -> pd.DataFrame:
    """
    Load Agent-5 rebalancing input.
    """

    if cfg.REBALANCING_INPUT_PARQUET.exists():

        dataframe = pd.read_parquet(
            cfg.REBALANCING_INPUT_PARQUET
        )

    elif cfg.REBALANCING_INPUT_CSV.exists():

        dataframe = pd.read_csv(
            cfg.REBALANCING_INPUT_CSV
        )

    else:

        raise FileNotFoundError(
            "Agent-5 rebalancing input not found."
        )

    return dataframe


def normalize_bool(
    series: pd.Series,
) -> pd.Series:
    """
    Normalize boolean representation.
    """

    if series.dtype == bool:

        return series

    return (
        series
        .astype(str)
        .str.strip()
        .str.lower()
        .isin(
            [
                "true",
                "1",
                "yes",
            ]
        )
    )



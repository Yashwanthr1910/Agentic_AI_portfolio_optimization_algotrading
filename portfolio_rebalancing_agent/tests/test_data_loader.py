def test_agent3_and_agent4_symbols_match():
    """
    Agent-3 risk output and Agent-4 trade output must refer to the same
    final stock universe entering Agent 5.
    """

    if cfg.AGENT3_RISK_PARQUET.exists():

        agent3 = pd.read_parquet(
            cfg.AGENT3_RISK_PARQUET
        )

    else:

        agent3 = pd.read_csv(
            cfg.AGENT3_RISK_CSV
        )

    if cfg.AGENT4_TRADE_DECISIONS_PARQUET.exists():

        agent4 = pd.read_parquet(
            cfg.AGENT4_TRADE_DECISIONS_PARQUET
        )

    else:

        agent4 = pd.read_csv(
            cfg.AGENT4_TRADE_DECISIONS_CSV
        )

    agent3_symbols = set(
        agent3[
            "symbol"
        ]
        .astype(str)
        .str.strip()
    )

    agent4_symbols = set(
        agent4[
            "symbol"
        ]
        .astype(str)
        .str.strip()
    )

    assert agent3_symbols == agent4_symbols
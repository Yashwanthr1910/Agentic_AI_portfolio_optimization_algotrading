# OPTIMIZER INPUT PREPARATION
# =============================================================================

def prepare_optimizer_inputs() -> dict[str, Any]:
    """
    Load and align all MPT inputs.

    Returns:
        returns
        eligible_returns
        rebalancing_input
        eligible_rows
        eligible_symbols
        expected_returns
        covariance
        target_return
    """

    returns = load_returns_matrix()

    rebalancing_input = (
        load_rebalancing_input()
    )

    rebalancing_input = (
        rebalancing_input
        .copy()
    )

    rebalancing_input[
        "symbol"
    ] = (
        rebalancing_input[
            "symbol"
        ]
        .astype(str)
        .str.strip()
    )

    rebalancing_input[
        "trade_action"
    ] = (
        rebalancing_input[
            "trade_action"
        ]
        .astype(str)
        .str.upper()
        .str.strip()
    )

    rebalancing_input[
        "eligible_for_mpt"
    ] = normalize_boolean_series(
        rebalancing_input[
            "eligible_for_mpt"
        ]
    )

    # -------------------------------------------------------------------------
    # VALIDATE ACTIONS
    # -------------------------------------------------------------------------

    if not rebalancing_input[
        "trade_action"
    ].isin(
        cfg.VALID_ACTIONS
    ).all():

        invalid = (
            rebalancing_input.loc[
                ~rebalancing_input[
                    "trade_action"
                ].isin(
                    cfg.VALID_ACTIONS
                ),
                "trade_action",
            ]
            .unique()
            .tolist()
        )

        raise ValueError(
            "Invalid trade actions found:\n"
            f"{invalid}"
        )

    # -------------------------------------------------------------------------
    # MPT-ELIGIBLE ASSETS
    # -------------------------------------------------------------------------

    eligible_rows = (
        rebalancing_input.loc[
            rebalancing_input[
                "eligible_for_mpt"
            ]
        ]
        .copy()
        .reset_index(
            drop=True
        )
    )

    if eligible_rows.empty:

        raise ValueError(
            "No MPT-eligible assets are available."
        )

    eligible_symbols = (
        eligible_rows[
            "symbol"
        ]
        .tolist()
    )

    # -------------------------------------------------------------------------
    # VERIFY BUY/HOLD ELIGIBILITY
    # -------------------------------------------------------------------------

    if not eligible_rows[
        "trade_action"
    ].isin(
        cfg.MPT_ELIGIBLE_ACTIONS
    ).all():

        raise ValueError(
            "An MPT-eligible stock has an invalid "
            "Agent-4 action."
        )

    # -------------------------------------------------------------------------
    # VERIFY SELL EXCLUSION
    # -------------------------------------------------------------------------

    sell_rows = (
        rebalancing_input[
            "trade_action"
        ]
        ==
        cfg.ACTION_SELL
    )

    if sell_rows.any():

        if rebalancing_input.loc[
            sell_rows,
            "eligible_for_mpt",
        ].any():

            raise ValueError(
                "A SELL stock is incorrectly eligible "
                "for MPT optimization."
            )

    # -------------------------------------------------------------------------
    # RETURN MATRIX ALIGNMENT
    # -------------------------------------------------------------------------

    missing_return_symbols = [
        symbol
        for symbol in eligible_symbols
        if symbol not in returns.columns
    ]

    if missing_return_symbols:

        raise ValueError(
            "MPT assets missing from returns matrix:\n"
            +
            "\n".join(
                missing_return_symbols
            )
        )

    eligible_returns = (
        returns[
            eligible_symbols
        ]
        .copy()
    )

    if eligible_returns.empty:

        raise ValueError(
            "Eligible return matrix is empty."
        )

    if not np.isfinite(
        eligible_returns.to_numpy(
            dtype=float
        )
    ).all():

        raise ValueError(
            "Eligible return matrix contains "
            "invalid numerical values."
        )

    # -------------------------------------------------------------------------
    # EXPECTED RETURNS
    # -------------------------------------------------------------------------
    #
    # Markowitz mean-return input.
    #
    # Arithmetic annualization is used here because:
    #
    #     E[Rannual] ≈ E[Rdaily] × 252
    #
    # and covariance is also annualized by ×252.
    # -------------------------------------------------------------------------

    expected_returns = (
        eligible_returns.mean()
        *
        cfg.TRADING_DAYS_PER_YEAR
    )

    expected_returns = expected_returns.reindex(
        eligible_symbols
    )

    if expected_returns.isna().any():

        raise ValueError(
            "Expected return vector contains missing values."
        )

    # -------------------------------------------------------------------------
    # COVARIANCE
    # -------------------------------------------------------------------------

    covariance = load_covariance_matrix()

    missing_covariance_symbols = [
        symbol
        for symbol in eligible_symbols
        if (
            symbol not in covariance.columns
            or
            symbol not in covariance.index
        )
    ]

    if missing_covariance_symbols:

        raise ValueError(
            "Eligible assets missing from covariance matrix:\n"
            +
            "\n".join(
                missing_covariance_symbols
            )
        )

    covariance = covariance.loc[
        eligible_symbols,
        eligible_symbols,
    ]

    # -------------------------------------------------------------------------
    # TARGET RETURN
    # -------------------------------------------------------------------------
    #
    # Paper-aligned interpretation:
    #
    # target return = average return of eligible assets.
    #
    # Since an equal-weight portfolio gives the arithmetic average
    # of individual expected returns, it is automatically feasible.
    # -------------------------------------------------------------------------

    target_return = float(
        expected_returns.mean()
    )

    return {
        "returns":
            returns,

        "eligible_returns":
            eligible_returns,

        "rebalancing_input":
            rebalancing_input,

        "eligible_rows":
            eligible_rows,

        "eligible_symbols":
            eligible_symbols,

        "expected_returns":
            expected_returns,

        "covariance":
            covariance,

        "target_return":
            target_return,
    }


# =============================================================================
# RAW OBJECTIVE
# =============================================================================

def variance_objective(
    weights: np.ndarray,
    covariance_matrix: np.ndarray,
) -> float:
    """
    Markowitz minimum-variance objective.

        objective = w.T @ covariance @ w

    This function intentionally performs no weight-sum validation because
    SLSQP evaluates trial points that may temporarily violate constraints.
    """

    weights = np.asarray(
        weights,
        dtype=float,
    )

    covariance_matrix = np.asarray(
        covariance_matrix,
        dtype=float,
    )

    value = float(
        weights.T
        @
        covariance_matrix
        @
        weights
    )

    return value


# =============================================================================
# WEIGHT-SUM CONSTRAINT
# =============================================================================

def weight_sum_constraint(
    weights: np.ndarray,
) -> float:
    """
    Equality constraint:

        sum(weights) = 1
    """

    return float(
        np.sum(
            weights
        )
        -
        cfg.WEIGHT_SUM_TARGET
    )


# =============================================================================
# TARGET-RETURN CONSTRAINT
# =============================================================================

def target_return_constraint(
    weights: np.ndarray,
    expected_returns: np.ndarray,
    target_return: float,
) -> float:
    """
    Equality constraint:

        w.T @ expected_returns = target_return
    """

    return float(
        np.dot(
            weights,
            expected_returns,
        )
        -
        target_return
    )


# =============================================================================
# MARKOWITZ OPTIMIZATION
# =============================================================================

def optimize_minimum_variance(
    expected_returns: pd.Series,
    covariance: pd.DataFrame,
    target_return: float,
) -> dict[str, Any]:
    """
    Solve the constrained Markowitz optimization.

    Minimize:

        w.T Σ w

    Subject to:

        Σ w = 1

        w.T μ = target return

        MIN_WEIGHT <= wi <= MAX_WEIGHT
    """

    symbols = (
        expected_returns.index
        .astype(str)
        .tolist()
    )

    number_of_assets = len(
        symbols
    )

    if number_of_assets < 1:

        raise ValueError(
            "No assets supplied to MPT optimizer."
        )

    covariance = covariance.loc[
        symbols,
        symbols,
    ]

    expected_return_vector = (
        expected_returns
        .to_numpy(
            dtype=float
        )
    )

    covariance_matrix = (
        covariance
        .to_numpy(
            dtype=float
        )
    )

    if not np.isfinite(
        expected_return_vector
    ).all():

        raise ValueError(
            "Expected returns contain invalid values."
        )

    if not np.isfinite(
        covariance_matrix
    ).all():

        raise ValueError(
            "Covariance contains invalid values."
        )

    # -------------------------------------------------------------------------
    # EQUAL-WEIGHT STARTING POINT
    # -------------------------------------------------------------------------
    #
    # Because target return is the mean asset return, equal weights
    # satisfy both equality constraints by construction.
    # -------------------------------------------------------------------------

    initial_weights = np.full(
        number_of_assets,
        1.0
        /
        number_of_assets,
        dtype=float,
    )

    initial_expected_return = float(
        np.dot(
            initial_weights,
            expected_return_vector,
        )
    )

    initial_variance = variance_objective(
        weights=initial_weights,
        covariance_matrix=covariance_matrix,
    )

    # -------------------------------------------------------------------------
    # BOUNDS
    # -------------------------------------------------------------------------

    bounds = [
        (
            cfg.MIN_WEIGHT,
            cfg.MAX_WEIGHT,
        )
        for _ in range(
            number_of_assets
        )
    ]

    # -------------------------------------------------------------------------
    # CONSTRAINTS
    # -------------------------------------------------------------------------

    constraints = [
        {
            "type":
                "eq",

            "fun":
                weight_sum_constraint,
        },

        {
            "type":
                "eq",

            "fun":
                lambda weights: target_return_constraint(
                    weights=weights,
                    expected_returns=expected_return_vector,
                    target_return=target_return,
                ),
        },
    ]

    # -------------------------------------------------------------------------
    # OPTIMIZE
    # -------------------------------------------------------------------------

    result = minimize(
        fun=variance_objective,

        x0=initial_weights,

        args=(
            covariance_matrix,
        ),

        method=cfg.OPTIMIZER_METHOD,

        bounds=bounds,

        constraints=constraints,

        options={
            "maxiter":
                cfg.OPTIMIZER_MAX_ITERATIONS,

            "ftol":
                cfg.OPTIMIZER_FTOL,

            "disp":
                False,
        },
    )

    if not result.success:

        raise RuntimeError(
            "Markowitz optimization failed.\n"
            f"Status : {result.status}\n"
            f"Message: {result.message}"
        )

    optimized_weights = np.asarray(
        result.x,
        dtype=float,
    )

    # Small floating-point values near zero.
    optimized_weights[
        np.abs(
            optimized_weights
        )
        <
        1e-12
    ] = 0.0

    weight_sum = float(
        optimized_weights.sum()
    )

    optimized_expected_return = float(
        np.dot(
            optimized_weights,
            expected_return_vector,
        )
    )

    optimized_variance = variance_objective(
        weights=optimized_weights,
        covariance_matrix=covariance_matrix,
    )

    optimized_volatility = float(
        np.sqrt(
            max(
                optimized_variance,
                0.0,
            )
        )
    )

    # -------------------------------------------------------------------------
    # FINAL CONSTRAINT VALIDATION
    # -------------------------------------------------------------------------

    checks = {
        "optimizer_success":
            bool(
                result.success
            ),

        "weights_finite":
            bool(
                np.isfinite(
                    optimized_weights
                ).all()
            ),

        "weights_nonnegative":
            bool(
                (
                    optimized_weights
                    >=
                    (
                        cfg.MIN_WEIGHT
                        -
                        cfg.FLOAT_TOLERANCE
                    )
                )
                .all()
            ),

        "weights_below_max":
            bool(
                (
                    optimized_weights
                    <=
                    (
                        cfg.MAX_WEIGHT
                        +
                        cfg.FLOAT_TOLERANCE
                    )
                )
                .all()
            ),

        "weights_sum_to_one":
            bool(
                np.isclose(
                    weight_sum,
                    cfg.WEIGHT_SUM_TARGET,
                    atol=cfg.WEIGHT_SUM_TOLERANCE,
                )
            ),

        "target_return_satisfied":
            bool(
                np.isclose(
                    optimized_expected_return,
                    target_return,
                    atol=cfg.TARGET_RETURN_TOLERANCE,
                )
            ),

        "variance_finite":
            bool(
                np.isfinite(
                    optimized_variance
                )
            ),

        "variance_nonnegative":
            bool(
                optimized_variance
                >=
                -cfg.FLOAT_TOLERANCE
            ),

        "variance_not_above_equal_weight":
            bool(
                optimized_variance
                <=
                (
                    initial_variance
                    +
                    1e-8
                )
            ),
    }

    if not all(
        checks.values()
    ):

        failed = [
            name
            for name, passed
            in checks.items()
            if not passed
        ]

        raise ValueError(
            "Optimized portfolio failed validation:\n"
            +
            "\n".join(
                f"  - {name}"
                for name
                in failed
            )
        )

    return {
        "symbols":
            symbols,

        "weights":
            optimized_weights,

        "initial_weights":
            initial_weights,

        "initial_return":
            initial_expected_return,

        "initial_variance":
            initial_variance,

        "target_return":
            target_return,

        "expected_return":
            optimized_expected_return,

        "variance":
            optimized_variance,

        "volatility":
            optimized_volatility,

        "optimizer_result":
            result,

        "checks":
            checks,
    }



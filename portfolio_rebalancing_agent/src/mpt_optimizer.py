    optimized_variance = (
        portfolio_variance(
            weights=optimized_weights,
            covariance_matrix=covariance.to_numpy(
                dtype=float
            ),
        )
    )

    optimized_volatility = (
        portfolio_volatility(
            weights=optimized_weights,
            covariance_matrix=covariance.to_numpy(
                dtype=float
            ),
        )
    )

    optimized_sharpe = (
        portfolio_sharpe_ratio(
            portfolio_return=optimized_expected_return,
            portfolio_volatility_value=optimized_volatility,
        )
    )

    # =========================================================================
    # HISTORICAL ESTIMATION-WINDOW METRICS
    # =========================================================================
    #
    # IMPORTANT:

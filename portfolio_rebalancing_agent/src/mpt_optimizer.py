# COVARIANCE MATRIX LOADER
# =============================================================================

def load_covariance_matrix() -> pd.DataFrame:
    """
    Load covariance matrix generated by data_loader.py.
    """

    if not cfg.COVARIANCE_MATRIX_CSV.exists():

        raise FileNotFoundError(
            "Covariance matrix was not found.\n"
            f"Expected:\n{cfg.COVARIANCE_MATRIX_CSV}\n\n"
            "Run Agent-5 data_loader.py first."
        )

    covariance = pd.read_csv(
        cfg.COVARIANCE_MATRIX_CSV,
        index_col=0,
    )

    covariance.index = (
        covariance.index
        .astype(str)
        .str.strip()
    )

    covariance.columns = (
        covariance.columns
        .astype(str)
        .str.strip()
    )

    covariance = covariance.apply(
        pd.to_numeric,
        errors="coerce",
    )

    if covariance.isna().any().any():

        raise ValueError(
            "Covariance matrix contains missing or "
            "non-numeric values."
        )

    covariance_values = covariance.to_numpy(
        dtype=float
    )

    if not np.isfinite(
        covariance_values
    ).all():

        raise ValueError(
            "Covariance matrix contains NaN or infinity."
        )

    if covariance.shape[0] != covariance.shape[1]:

        raise ValueError(
            "Covariance matrix is not square."
        )

    if not np.allclose(
        covariance_values,
        covariance_values.T,
        atol=1e-10,
    ):

        raise ValueError(
            "Covariance matrix is not symmetric."
        )

    return covariance



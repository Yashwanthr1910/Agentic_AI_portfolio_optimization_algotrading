def normalize_boolean_series(
    series: pd.Series,
) -> pd.Series:
    """
    Convert bool/string/integer representations into booleans.
    """

    if series.dtype == bool:

        return series.copy()

    return (
        series
        .astype(str)
        .str.strip()
        .str.lower()
        .isin(
            [
                "true",
                "1",
                "yes",
                "y",
            ]
        )
    )



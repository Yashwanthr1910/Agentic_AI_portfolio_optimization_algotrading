    # =========================================================================

    equal_historical_metrics = (
        calculate_portfolio_metrics(
            returns=eligible_returns,
            weights=equal_weights,
        )
    )

    optimized_historical_metrics = (
        calculate_portfolio_metrics(
            returns=eligible_returns,
            weights=optimized_weights,
            previous_weights=equal_weights,
        )
    )

    # =========================================================================
    # VARIANCE REDUCTION
    # =========================================================================

    if equal_variance > 0:

        variance_reduction = (
            (
                equal_variance
                -
                optimized_variance
            )
            /
            equal_variance
        )

    else:

        variance_reduction = 0.0

    if equal_volatility > 0:

        volatility_reduction = (
            (
                equal_volatility
                -
                optimized_volatility
            )
            /
            equal_volatility
        )

    else:

        volatility_reduction = 0.0

    # =========================================================================
    # DISPLAY OPTIMIZED WEIGHTS

# CREATE COMPLETE MPT SOLUTION TABLE
# =============================================================================

def build_mpt_solution(
    rebalancing_input: pd.DataFrame,
    returns: pd.DataFrame,
    eligible_symbols: list[str],
    optimized_weights: np.ndarray,
) -> pd.DataFrame:
    """
    Create a complete solution containing all ten Agent-4 stocks.

    Eligible BUY/HOLD stocks receive optimized MPT weights.

    SELL stocks receive exactly zero MPT weight.
    """

    solution = (
        rebalancing_input
        .copy()
    )

    solution[
        "symbol"
    ] = (
        solution[
            "symbol"
        ]
        .astype(str)
        .str.strip()
    )

    # -------------------------------------------------------------------------
    # EXPECTED RETURN FOR ALL STOCKS
    # -------------------------------------------------------------------------

    all_expected_returns = (
        returns.mean()
        *
        cfg.TRADING_DAYS_PER_YEAR
    )

    solution[
        "mpt_expected_return"
    ] = (
        solution[
            "symbol"
        ]
        .map(
            all_expected_returns
            .to_dict()
        )
    )

    # -------------------------------------------------------------------------
    # WEIGHT MAP
    # -------------------------------------------------------------------------

    weight_map = {
        symbol:
            float(
                weight
            )

        for symbol, weight
        in zip(
            eligible_symbols,
            optimized_weights,
        )
    }

    solution[
        "mpt_weight"
    ] = (
        solution[
            "symbol"
        ]
        .map(
            weight_map
        )
        .fillna(
            cfg.SELL_TARGET_WEIGHT
        )
        .astype(float)
    )

    solution[
        "mpt_allocation_percent"
    ] = (
        solution[
            "mpt_weight"
        ]
        *
        100.0
    )

    solution[
        "sell_zero_weight_enforced"
    ] = (
        solution[
            "trade_action"
        ]
        .astype(str)
        .str.upper()
        .eq(
            cfg.ACTION_SELL
        )
    )

    # -------------------------------------------------------------------------
    # RANK BY ALLOCATION
    # -------------------------------------------------------------------------

    solution[
        "mpt_allocation_rank"
    ] = (
        solution[
            "mpt_weight"
        ]
        .rank(
            method="dense",
            ascending=False,
        )
        .astype(int)
    )

    # -------------------------------------------------------------------------
    # SORT
    # -------------------------------------------------------------------------

    solution = (
        solution
        .sort_values(
            [
                "mpt_weight",
                "symbol",
            ],
            ascending=[
                False,
                True,
            ],
        )
        .reset_index(
            drop=True
        )
    )

    return solution


# =============================================================================
# FINAL SOLUTION VALIDATION
# =============================================================================

def validate_solution_table(
    solution: pd.DataFrame,
    eligible_symbols: list[str],
) -> dict[str, bool]:
    """
    Validate all-stock Agent-5 MPT solution.
    """

    weights = (
        solution[
            "mpt_weight"
        ]
        .to_numpy(
            dtype=float
        )
    )

    sell_rows = (
        solution[
            "trade_action"
        ]
        .astype(str)
        .str.upper()
        .eq(
            cfg.ACTION_SELL
        )
    )

    eligible_rows = (
        solution[
            "symbol"
        ]
        .isin(
            eligible_symbols
        )
    )

    checks = {
        "solution_not_empty":
            not solution.empty,

        "one_row_per_symbol":
            not solution[
                "symbol"
            ]
            .duplicated()
            .any(),

        "weights_finite":
            bool(
                np.isfinite(
                    weights
                ).all()
            ),

        "weights_nonnegative":
            bool(
                (
                    weights
                    >=
                    (
                        cfg.MIN_WEIGHT
                        -
                        cfg.FLOAT_TOLERANCE
                    )
                )
                .all()
            ),

        "weights_sum_to_one":
            bool(
                np.isclose(
                    weights.sum(),
                    cfg.WEIGHT_SUM_TARGET,
                    atol=cfg.WEIGHT_SUM_TOLERANCE,
                )
            ),

        "sell_weights_zero":
            bool(
                np.allclose(
                    solution.loc[
                        sell_rows,
                        "mpt_weight",
                    ]
                    .to_numpy(
                        dtype=float
                    ),
                    cfg.SELL_TARGET_WEIGHT,
                    atol=cfg.FLOAT_TOLERANCE,
                )
            ),

        "eligible_assets_match":
            set(
                solution.loc[
                    eligible_rows,
                    "symbol",
                ]
            )
            ==
            set(
                eligible_symbols
            ),

        "all_positive_weights_belong_to_eligible_assets":
            bool(
                solution.loc[
                    solution[
                        "mpt_weight"
                    ]
                    >
                    cfg.FLOAT_TOLERANCE,
                    "symbol",
                ]
                .isin(
                    eligible_symbols
                )
                .all()
            ),
    }

    return checks



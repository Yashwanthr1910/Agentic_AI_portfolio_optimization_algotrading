"""
Agent 5 - RL Feedback Layer
===============================================================================

PROJECT
-------
Agentic AI Portfolio Optimization and Algorithmic Trading

AGENT
-----
Agent 5 - Portfolio Rebalancing Agent

PURPOSE
-------
Combine:

    Agent-4 DQN trade decisions

with:

    Agent-5 Markowitz MPT optimized weights

to produce the RL-aware portfolio allocation used by the final
rebalancing agent.


PIPELINE
--------
Agent 4 DQN
BUY / SELL / HOLD
        |
        v
Agent 5 MPT
minimum-variance weights
        |
        v
RL Feedback Layer
        |
        +---- SELL -> force weight = 0
        |
        +---- BUY  -> preserve MPT allocation
        |
        +---- HOLD -> preserve MPT allocation
        |
        v
Normalize remaining allocation
        |
        v
RL-adjusted portfolio weights


REFERENCE-PAPER INTERPRETATION
------------------------------
The reference paper combines Markowitz MPT with reinforcement learning
for portfolio rebalancing.

The paper does not provide a complete software-level equation that maps
DQN BUY / SELL / HOLD actions into numerical portfolio weights.

Therefore this implementation uses a transparent reconstruction:

    SELL -> zero allocation

    BUY  -> MPT determines allocation

    HOLD -> MPT determines allocation

No arbitrary BUY multiplier is introduced.

No arbitrary HOLD multiplier is introduced.

This avoids inventing parameters that are not reported in the paper.


IMPORTANT
---------
Agent 4 is already the learned DQN reinforcement-learning component.

This module does NOT train another neural network.

Instead, it transfers the DQN action into the portfolio-rebalancing
decision layer.
"""


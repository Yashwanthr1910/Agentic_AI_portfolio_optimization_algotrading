def load_mpt_solution() -> pd.DataFrame:
    """
    Load mpt_solution.csv generated by mpt_optimizer.py.
    """

    if not cfg.MPT_SOLUTION_CSV.exists():

        raise FileNotFoundError(
            "MPT solution was not found.\n\n"
            f"Expected:\n"
            f"{cfg.MPT_SOLUTION_CSV}\n\n"
            "Run mpt_optimizer.py first."
        )

    dataframe = pd.read_csv(
        cfg.MPT_SOLUTION_CSV,
        low_memory=False,
    )

    if dataframe.empty:

        raise ValueError(
            "MPT solution is empty."
        )

    required_columns = {
        "symbol",
        "trade_action",
        "mpt_weight",
    }

    missing_columns = (
        required_columns
        -
        set(
            dataframe.columns
        )
    )

    if missing_columns:

        raise ValueError(
            "MPT solution is missing required columns:\n"
            +
            "\n".join(
                sorted(
                    missing_columns
                )
            )
        )

    dataframe = dataframe.copy()

    dataframe[
        "symbol"
    ] = (
        dataframe[
            "symbol"
        ]
        .astype(str)
        .str.strip()
    )

    dataframe[
        "trade_action"
    ] = (
        dataframe[
            "trade_action"
        ]
        .astype(str)
        .str.upper()
        .str.strip()
    )

    dataframe[
        "mpt_weight"
    ] = pd.to_numeric(
        dataframe[
            "mpt_weight"
        ],
        errors="coerce",
    )

    if dataframe[
        "symbol"
    ].duplicated().any():

        duplicated = (
            dataframe.loc[
                dataframe[
                    "symbol"
                ].duplicated(
                    keep=False
                ),
                "symbol",
            ]
            .tolist()
        )

        raise ValueError(
            "Duplicate symbols in MPT solution:\n"
            +
            "\n".join(
                sorted(
                    set(
                        duplicated
                    )
                )
            )
        )

    if dataframe[
        "mpt_weight"
    ].isna().any():

        raise ValueError(
            "MPT solution contains invalid weights."
        )

    if not np.isfinite(
        dataframe[
            "mpt_weight"
        ]
        .to_numpy(
            dtype=float
        )
    ).all():

        raise ValueError(
            "MPT weights contain NaN or infinity."
        )

    if not dataframe[
        "trade_action"
    ].isin(
        cfg.VALID_ACTIONS
    ).all():

        invalid_actions = (
            dataframe.loc[
                ~dataframe[
                    "trade_action"
                ].isin(
                    cfg.VALID_ACTIONS
                ),
                "trade_action",
            ]
            .unique()
            .tolist()
        )

        raise ValueError(
            "Invalid Agent-4 actions in MPT solution:\n"
            f"{invalid_actions}"
        )

    return dataframe


